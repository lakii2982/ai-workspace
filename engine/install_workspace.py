"""Initialize a data workspace and verify the core CLI and MCP service."""

import asyncio
import json
import os
from pathlib import Path
import shlex
import subprocess
import sys
import tomllib

from desktop_install import CLIENTS, codex_config, configure, config_json, detect
from mcp import ClientSession, StdioServerParameters
from mcp.client.stdio import stdio_client


def check_file(path: Path, content: str) -> None:
    if path.is_symlink() or (path.exists() and (
        not path.is_file() or path.read_text(encoding="utf-8") != content
    )):
        raise ValueError(f"Existing file differs: {path}. Choose a new workspace or resolve the conflict.")


def write_file(path: Path, content: str) -> None:
    try:
        with path.open("x", encoding="utf-8") as file:
            file.write(content)
    except FileExistsError:
        check_file(path, content)


def uses_working_legacy_launcher(existing, workspace: Path, **fields) -> bool:
    legacy = workspace / "aiws"
    if existing != {"command": str(legacy), "args": ["--mcp"], **fields}:
        return False
    if legacy.is_symlink() or not legacy.is_file() or not os.access(legacy, os.X_OK):
        return False
    runtime = Path(sys.executable).parent
    old_launcher = (
        "#!/bin/sh\n"
        "# Generated by AI WorkSpace.\n"
        f"AIWS_WORKSPACE={shlex.quote(str(workspace))}\n"
        "export AIWS_WORKSPACE\n"
        'if [ "${1:-}" = "--mcp" ]; then\n'
        f"    exec {shlex.quote(str(runtime / 'aiws-mcp'))}\n"
        "fi\n"
        f"exec {shlex.quote(str(runtime / 'aiws'))} --workspace \"$AIWS_WORKSPACE\" \"$@\"\n"
    )
    return legacy.read_text(encoding="utf-8") == old_launcher


def client_config(workspace: Path, launcher: Path, agent: str):
    server = {"command": str(launcher), "args": ["--mcp"], "env": {"AIWS_WORKSPACE": str(workspace)}}
    if agent == "codex":
        path = workspace / ".codex" / "config.toml"
        old = tomllib.loads(path.read_text()).get("mcp_servers", {}).get("aiws") if path.exists() else None
        legacy = dict(old or {})
        legacy.pop("tools", None)
        codex_config(path, server, uses_working_legacy_launcher(legacy, workspace))
    elif agent == "claude":
        path = workspace / ".mcp.json"
        existing = json.loads(path.read_text()).get("mcpServers", {}).get("aiws") if path.exists() else None
        if not uses_working_legacy_launcher(existing, workspace, type="stdio"):
            config_json(path, {"type": "stdio", **server})
    return None


async def check_mcp(launcher: Path, workspace: Path) -> None:
    params = StdioServerParameters(
        command=str(launcher), args=["--mcp"], env={"AIWS_WORKSPACE": str(workspace)},
    )
    async with stdio_client(params) as (receive, send):
        async with ClientSession(receive, send) as session:
            await session.initialize()
            response = await session.call_tool("list_projects", {"limit": 1})
    if response.isError:
        raise ValueError("MCP list_projects returned a tool error.")
    result = response.structuredContent
    if result is None and response.content and response.content[0].type == "text":
        result = json.loads(response.content[0].text)
    if not isinstance(result, dict) or result.get("ok") is not True:
        raise ValueError("MCP list_projects did not return a successful result.")


def install(workspace: Path, agent: str) -> None:
    source = Path(__file__).resolve().parent.parent
    if workspace == source or source in workspace.parents or workspace in source.parents:
        raise ValueError("Choose a workspace directory separate from the source checkout.")

    launcher = source / "aiws"
    state = workspace / ".workspace"
    marker = state / "config.json"
    initialized = not state.is_symlink() and not marker.is_symlink() and marker.is_file()
    if workspace.exists() and (not workspace.is_dir() or (any(workspace.iterdir()) and not initialized)):
        raise ValueError("Choose a new or empty workspace directory.")

    legacy = workspace.parent / "aiws_core"
    if initialized and legacy != source and (legacy / "aiws").is_file():
        from upgrade import adopt_legacy
        if adopt_legacy(legacy, workspace):
            launcher = legacy / "aiws"

    documents = [
        (workspace / "AGENTS.md", (source / "AGENTS.md").read_text(encoding="utf-8")),
        (workspace / "START.md", (source / "WORKSPACE.md").read_text(encoding="utf-8")),
    ]
    if "claude" in agent.split(","):
        documents.append((workspace / "CLAUDE.md", "@AGENTS.md\n"))
    files = []
    for path, content in documents:
        if path.is_symlink() or (path.exists() and not path.is_file()):
            raise ValueError(f"Refusing to write workspace document: {path}")
        if not path.exists():
            files.append((path, content))

    clients = agent.split(",")
    if any(client not in (*CLIENTS, "claude", "cli") for client in clients):
        raise ValueError("Unknown desktop client")
    env = {**os.environ, "AIWS_WORKSPACE": str(workspace)}
    subprocess.run([str(launcher), "init"], check=True, stdout=subprocess.DEVNULL, env=env)
    for path, content in files:
        path.parent.mkdir(parents=True, exist_ok=True)
        write_file(path, content)

    response = subprocess.check_output([str(launcher), "doctor"], text=True, env=env)
    health = json.loads(response)
    if health.get("result", {}).get("healthy") is not True:
        raise ValueError(f"Workspace doctor failed: {response.strip()}")
    asyncio.run(asyncio.wait_for(check_mcp(launcher, workspace), timeout=30))
    desktop_results = []
    for client in dict.fromkeys(clients):
        try:
            client_config(workspace, launcher, client)
            if client in CLIENTS:
                desktop_results.append(configure(client, workspace, launcher, activate=True, source=source))
        except (OSError, ValueError, subprocess.SubprocessError) as exc:
            desktop_results.append(dict(client=client, status='blocked', detail=str(exc)))
    blocked = [result for result in desktop_results if result['status'] == 'blocked']
    print(json.dumps({
        "core": str(source), "workspace": str(workspace), "launcher": str(launcher),
        "ok": not blocked, "agent": agent, "clients": desktop_results, "doctor": "healthy", "mcp": "verified",
    }, ensure_ascii=False, indent=2))
    if blocked:
        raise SystemExit(1)


if __name__ == "__main__":
    try:
        if sys.argv[1:] == ["--detect"]:
            print(json.dumps(detect(), ensure_ascii=False))
            sys.exit(0)
        install(Path(sys.argv[1]).expanduser().resolve(), sys.argv[2])
    except Exception as exc:
        raise SystemExit(f"AI WorkSpace setup failed: {exc}") from None
