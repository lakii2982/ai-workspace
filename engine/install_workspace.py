"""Create the local entry points and verify a new workspace."""

import asyncio
import json
from pathlib import Path
import shlex
import subprocess
import sys
import tomllib

from mcp import ClientSession, StdioServerParameters
from mcp.client.stdio import stdio_client


def check_file(path: Path, content: str) -> None:
    if path.is_symlink() or (path.exists() and (
        not path.is_file() or path.read_text(encoding="utf-8") != content
    )):
        raise ValueError(f"Existing file differs: {path}. Choose a new workspace or resolve the conflict.")


def write_file(path: Path, content: str) -> None:
    try:
        with path.open("x", encoding="utf-8") as file:
            file.write(content)
    except FileExistsError:
        check_file(path, content)


def client_config(workspace: Path, launcher: Path, agent: str):
    command = str(launcher)
    if agent == "codex":
        path = workspace / ".codex" / "config.toml"
        body = f'[mcp_servers.aiws]\ncommand = {json.dumps(command, ensure_ascii=False)}\nargs = ["--mcp"]\n'
        if path.is_file() and not path.is_symlink() and not path.parent.is_symlink():
            existing = tomllib.loads(path.read_text(encoding="utf-8")).get("mcp_servers", {}).get("aiws")
            if existing == {"command": command, "args": ["--mcp"]}:
                return None
        return path, body
    if agent == "claude":
        path = workspace / ".mcp.json"
        server = {"type": "stdio", "command": command, "args": ["--mcp"]}
        if path.is_file() and not path.is_symlink():
            existing = json.loads(path.read_text(encoding="utf-8")).get("mcpServers", {}).get("aiws")
            if existing == server:
                return None
        return path, json.dumps({"mcpServers": {"aiws": server}}, ensure_ascii=False, indent=2) + "\n"
    return None


async def check_mcp(launcher: Path) -> None:
    params = StdioServerParameters(command=str(launcher), args=["--mcp"])
    async with stdio_client(params) as (receive, send):
        async with ClientSession(receive, send) as session:
            await session.initialize()
            response = await session.call_tool("list_projects", {"limit": 1})
    if response.isError:
        raise ValueError("MCP list_projects returned a tool error.")
    result = response.structuredContent
    if result is None and response.content and response.content[0].type == "text":
        result = json.loads(response.content[0].text)
    if not isinstance(result, dict) or result.get("ok") is not True:
        raise ValueError("MCP list_projects did not return a successful result.")


def install(workspace: Path, agent: str) -> None:
    engine = Path(__file__).resolve().parent
    source = engine.parent
    if workspace == source or source in workspace.parents or workspace in source.parents:
        raise ValueError("Choose a workspace directory separate from the source checkout.")

    launcher = workspace / "aiws"
    root = shlex.quote(str(workspace))
    runtime = Path(sys.executable).parent
    launcher_text = (
        "#!/bin/sh\n"
        "# Generated by AI WorkSpace.\n"
        f"AIWS_WORKSPACE={root}\n"
        "export AIWS_WORKSPACE\n"
        'if [ "${1:-}" = "--mcp" ]; then\n'
        f"    exec {shlex.quote(str(runtime / 'aiws-mcp'))}\n"
        "fi\n"
        f"exec {shlex.quote(str(runtime / 'aiws'))} --workspace \"$AIWS_WORKSPACE\" \"$@\"\n"
    )
    if workspace.exists() and any(workspace.iterdir()) and not launcher.is_file():
        raise ValueError("Choose a new or empty workspace directory.")
    rules = (source / "AGENTS.md").read_text(encoding="utf-8")
    intro = (source / "WORKSPACE.md").read_text(encoding="utf-8")
    files = [(launcher, launcher_text), (workspace / "AGENTS.md", rules), (workspace / "START.md", intro)]
    if agent == "claude":
        files.append((workspace / "CLAUDE.md", "@AGENTS.md\n"))
    config = client_config(workspace, launcher, agent)
    if config:
        files.append(config)
    for path, content in files:
        if path.parent.is_symlink():
            raise ValueError(f"Refusing symbolic link: {path.parent}")
        check_file(path, content)

    for path, content in files:
        path.parent.mkdir(parents=True, exist_ok=True)
        write_file(path, content)
    launcher.chmod(0o755)

    subprocess.run([str(launcher), "init"], check=True, stdout=subprocess.DEVNULL)
    response = subprocess.check_output([str(launcher), "doctor"], text=True)
    health = json.loads(response)
    if health.get("result", {}).get("healthy") is not True:
        raise ValueError(f"Workspace doctor failed: {response.strip()}")
    asyncio.run(asyncio.wait_for(check_mcp(launcher), timeout=30))
    print(json.dumps({"workspace": str(workspace), "agent": agent, "doctor": "healthy", "mcp": "verified"},
                     ensure_ascii=False, indent=2))


if __name__ == "__main__":
    try:
        install(Path(sys.argv[1]).expanduser().resolve(), sys.argv[2])
    except Exception as exc:
        raise SystemExit(f"AI WorkSpace setup failed: {exc}") from None
